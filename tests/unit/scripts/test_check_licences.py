"""The licence check refuses what it cannot read, and an exception lasts only as long as its facts.

`.github/scripts/check_licences.py` asks PyPI over the network, which the unit tier may not
do. Everything it decides is a pure function of the metadata PyPI returns, so the decisions
are pinned here against metadata written out by hand.
"""

import importlib.util
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[3]


def load_tool() -> ModuleType:
    """Import `.github/scripts/check_licences.py`; registered first, as `dataclass` requires."""
    spec = importlib.util.spec_from_file_location(
        "check_licences", ROOT / ".github" / "scripts" / "check_licences.py"
    )
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


tool = load_tool()


def status(name: str, metadata: dict[str, Any]) -> str:
    """The verdict on one release of `name` declaring `metadata`."""
    verdict: Any = tool.judge(name, "1.0", metadata)
    found: str = verdict.status
    return found


@pytest.mark.parametrize(
    ("expression", "refused"),
    [
        ("MIT", []),
        ("Apache-2.0 AND MIT", []),
        ("MIT OR GPL-3.0-only", []),
        ("GPL-3.0-only OR MIT", []),
        ("Apache-2.0 AND GPL-3.0-only", ["GPL-3.0-only"]),
        ("MPL-2.0 AND (Apache-2.0 OR MIT)", []),
        ("(GPL-2.0-only OR AGPL-3.0-only) AND MIT", ["GPL-2.0-only", "AGPL-3.0-only"]),
        ("Apache-2.0 WITH LLVM-exception", []),
        ("GPL-2.0-only WITH Classpath-exception-2.0", ["GPL-2.0-only"]),
    ],
)
def test_an_spdx_expression_is_judged_by_its_operators(expression: str, refused: list[str]) -> None:
    """Every side of AND must be allowed, one side of OR suffices, WITH only adds rights."""
    assert tool.disallowed(expression) == refused


@pytest.mark.parametrize("text", ["", "MIT AND", "(MIT", "MIT)", "Dual License", "BSD, MIT"])
def test_text_that_is_not_an_expression_is_not_read_as_one(text: str) -> None:
    with pytest.raises(tool.UnreadableError):
        tool.disallowed(text)


def test_a_pep_639_expression_wins_over_everything_else() -> None:
    metadata = {
        "license_expression": "GPL-3.0-only",
        "license": "MIT",
        "classifiers": ["License :: OSI Approved :: MIT License"],
    }

    assert status("example", metadata) == "refused"


def test_a_known_free_text_spelling_is_read_as_its_licence() -> None:
    assert status("example", {"license": "Apache License, Version 2.0"}) == "allowed"


def test_a_licence_text_pasted_into_the_field_falls_through_to_the_classifiers() -> None:
    metadata = {
        "license": "Copyright (c) someone\n\nPermission is hereby granted ...",
        "classifiers": ["License :: OSI Approved :: BSD License"],
    }

    assert status("example", metadata) == "allowed"


def test_every_licence_classifier_must_be_allowed() -> None:
    metadata = {
        "classifiers": [
            "License :: OSI Approved :: MIT License",
            "License :: OSI Approved :: GNU General Public License v3 (GPLv3)",
        ]
    }

    assert status("example", metadata) == "undetermined"


def test_a_release_that_declares_nothing_fails_rather_than_passes() -> None:
    """A tool that could not tell is how an unlicensed package would get in."""
    verdict: Any = tool.judge("example", "1.0", {"license": "", "classifiers": []})

    assert verdict.status == "undetermined"
    assert not verdict.passed


def test_a_reviewed_exception_holds_only_while_the_declaration_is_unchanged() -> None:
    assert status("psycopg", {"license_expression": "LGPL-3.0-only"}) == "reviewed"
    assert status("psycopg", {"license_expression": "GPL-3.0-only"}) == "refused"


def test_a_vendor_family_is_reviewed_by_prefix() -> None:
    assert status("nvidia-cublas", {}) == "reviewed"
    assert status("nvidia-something-new", {"license_expression": "MIT"}) == "refused"


def test_an_exception_whose_package_left_the_lockfile_is_reported_stale() -> None:
    present = {"psycopg", "psycopg-binary", "psycopg-pool", "pypdfium2", "nvidia-cublas"}

    assert tool.stale_reviews(present) == ["cuda-toolkit"]


def test_the_export_is_read_once_per_release_whatever_its_markers() -> None:
    export = "\n".join(
        [
            "# This file was autogenerated by uv",
            "grpcio==1.78.2 ; sys_platform != 'emscripten'",
            "grpcio==1.85.0 ; sys_platform == 'emscripten'",
            "Typing_Extensions==4.15.0",
            "    # via pydantic",
            "typing-extensions==4.15.0 ; python_full_version < '3.13'",
        ]
    )

    assert tool.locked_releases(export) == [
        ("grpcio", "1.78.2"),
        ("grpcio", "1.85.0"),
        ("typing-extensions", "4.15.0"),
    ]
